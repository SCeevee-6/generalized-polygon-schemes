"""Shared helpers for the GO(2,4) computations in flags/ and triple/.

Everything is built from the ATLAS permutation representation of 2F4(2) = T.2 on the 1755 points of the
Ree-Tits octagon (TF42d2G1-p1755B0, standard generators c, d). T = 2F4(2)' is the subgroup generated by
c and (cdcdcdcd)^(dcddcdcddd) (ATLAS, maximal subgroups of 2F4(2)). Permutations are numpy arrays with
g[x] = image of x; products read left to right as in GAP, so x^(gh) = h[g[x]].

The ATLAS files are cached in flags/atlas_cache/ (git-ignored).
"""
import os, re
import numpy as np, requests

HERE = os.path.dirname(os.path.abspath(__file__))
CACHE = os.path.join(HERE, 'atlas_cache')
URL = 'https://brauer.maths.qmul.ac.uk/Atlas/exc/TF42/gap/{}.{}'
N = 1755


def load_gap_perm(name, g):
    os.makedirs(CACHE, exist_ok=True)
    f = os.path.join(CACHE, f'{name}.{g}')
    if not os.path.exists(f):
        open(f, 'w').write(requests.get(URL.format(name, g), timeout=120).text)
    t = open(f).read()
    perm = np.arange(N)
    for cyc in re.findall(r'\(([\d,\s]+)\)', t[t.find('('):]):
        pts = [int(x) - 1 for x in re.sub(r'\s', '', cyc).split(',')]
        for x, y in zip(pts, pts[1:] + pts[:1]):
            perm[x] = y
    return perm


def mul(*gs):
    """Left-to-right product g1 g2 ... (apply g1 first)."""
    r = np.arange(len(gs[0]))
    for g in gs:
        r = g[r]
    return r


def inv(g):
    r = np.empty_like(g); r[g] = np.arange(len(g)); return r


def word(w, gens):
    return mul(*[gens[ch] for ch in w])


def generators():
    """Return (T_gens, T2_gens) on 1755 points, same numbering."""
    c, d = load_gap_perm('TF42d2G1-p1755B0', 'g1'), load_gap_perm('TF42d2G1-p1755B0', 'g2')
    G = {'c': c, 'd': d}
    x, y = word('cdcdcdcd', G), word('dcddcdcddd', G)
    t2 = mul(inv(y), x, y)
    return [c, t2], [c, d]


def group_order(gens):
    from sympy.combinatorics import Permutation, PermutationGroup
    return PermutationGroup([Permutation(list(map(int, g))) for g in gens]).order()


def stabiliser_gens(gens, n, pt=0, order=None, maxgens=None):
    """Schreier generators t_x g t_{xg}^{-1} of the stabiliser of pt, skipping trivial ones and ones that
    do not merge stabiliser orbits. If `order` is given (the stabiliser order), generators are added
    until the generated group has that order (checked with sympy), so the result provably generates it."""
    tr = {pt: np.arange(n)}
    seq = [pt]
    for x in seq:
        for g in gens:
            y = int(g[x])
            if y not in tr:
                tr[y] = mul(tr[x], g); seq.append(y)
    assert len(tr) == n
    out, comp = [], np.arange(n)
    ident = np.arange(n)
    for x in seq:
        for g in gens:
            s = mul(tr[x], g, inv(tr[int(g[x])]))
            assert s[pt] == pt
            if np.array_equal(s, ident):
                continue
            if order is None and np.array_equal(comp[s], comp):
                continue
            out.append(s)
            from scipy.sparse import coo_matrix
            from scipy.sparse.csgraph import connected_components
            k = comp.max() + 1
            A = coo_matrix((np.ones(n), (comp, comp[s])), shape=(k, k))
            comp = connected_components(A, directed=True, connection='weak')[1][comp]
            if order is not None and len(out) % 4 == 0 and group_order(out) == order:
                return out
            if maxgens and len(out) >= maxgens:
                return out
    if order is not None:
        assert group_order(out) == order
    return out


def orbits(gens, n):
    """Orbit labels of the group generated by gens on range(n)."""
    from scipy.sparse import coo_matrix
    from scipy.sparse.csgraph import connected_components
    A = coo_matrix((np.ones(n * len(gens)), (np.tile(np.arange(n), len(gens)), np.concatenate(gens))), shape=(n, n))
    return connected_components(A, directed=True, connection='weak')[1]


def point_distances(Tg):
    """Distance matrix (int8) of the collinearity graph; the neighbours of 0 are the orbit of length 10."""
    from scipy.sparse import csr_matrix
    from scipy.sparse.csgraph import shortest_path
    lab = orbits(stabiliser_gens(Tg, N), N)
    sizes = np.bincount(lab)
    nb = np.nonzero(sizes[lab] == 10)[0]
    assert len(nb) == 10
    edges = set((0, int(v)) for v in nb)
    frontier = list(edges)
    while frontier:
        new = []
        for (a, b) in frontier:
            for g in Tg:
                e = (int(g[a]), int(g[b]))
                if e not in edges:
                    edges.add(e); new.append(e)
        frontier = new
    e = np.array(sorted(edges))
    M = csr_matrix((np.ones(len(e), np.int8), (e[:, 0], e[:, 1])), shape=(N, N))
    return shortest_path(M, unweighted=True, directed=False).astype(np.int8)


def lines_from_distances(D):
    """Lines = triangles of the collinearity graph (girth 16 in the incidence graph)."""
    L = set()
    for x in range(N):
        nb = np.nonzero(D[x] == 1)[0]
        for y in nb:
            if y > x:
                z = [int(w) for w in nb if w != y and D[y, w] == 1]
                assert len(z) == 1
                L.add(tuple(sorted((x, int(y), z[0]))))
    return sorted(L)
